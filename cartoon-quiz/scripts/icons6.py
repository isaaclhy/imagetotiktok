from PIL import Image, ImageDraw
import math
S=4
def _c(n,bg):
    im=Image.new("RGBA",(400*S,400*S),bg+(255,)); return im,ImageDraw.Draw(im)
def E(d,x0,y0,x1,y1,f,o=None,w=0): d.ellipse([v*S for v in(x0,y0,x1,y1)],fill=f,outline=o,width=w*S)
def R(d,x0,y0,x1,y1,f,r=0): d.rounded_rectangle([v*S for v in(x0,y0,x1,y1)],r*S,fill=f)
def P(d,pts,f): d.polygon([(x*S,y*S) for x,y in pts],fill=f)
def L(d,pts,f,w): d.line([(x*S,y*S) for x,y in pts],fill=f,width=w*S,joint="curve")
