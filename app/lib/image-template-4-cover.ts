/** Randomly picks one of the cover prompts on each generation. */
export function pickRandomImageTemplate4CoverPrompt(): {
  prompt: string;
  variant: ImageTemplate4CoverPromptVariant;
} {
  const picked =
    IMAGE_TEMPLATE4_COVER_VARIANTS[
      Math.floor(Math.random() * IMAGE_TEMPLATE4_COVER_VARIANTS.length)
    ]!;
  return { variant: picked.variant, prompt: picked.prompt };
}

