let cached: CoverTemplate[] | null = null;

/** All static cover templates, deduped, in a stable order. */
export function coverTemplates(): CoverTemplate[] {
  if (cached) return cached;
  const seen = new Set<string>();
  const out: CoverTemplate[] = [];
  for (const template of [...SEED, ...HAND, ...expanded()]) {
    const key = `${template.tone}|${template.scope}|${template.text}`;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(template);
  }
  cached = out;
  return out;
}
