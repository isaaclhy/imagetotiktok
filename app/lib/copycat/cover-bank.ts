/**
 * Static Gen Z cover lines for Spill It copycat posts.
 * Tokens are filled per post so the wording matches who is being asked
 * and, where a number appears, the real question count.
 *
 * `{n}` question count, `{k}` a question number from 1..n,
 * `{who}` boyfriend/girlfriend/partner/bestie, `{short}` bf/gf/partner/bestie,
 * `{him}` him/her/them, `{he}` he/she/they, `{his}` his/her/their,
 * `{hes}` he's/she's/they're, `{hell}` he'll/she'll/they'll,
 * `{self}` himself/herself/themself,
 * `{s}` s or empty, `{es}` es or empty,
 * `{is}` is/are, `{has}` has/have, `{was}` was/were, `{does}` does/do.
 */

export type CoverTone =
  | 'cheat'
  | 'jealous'
  | 'redflag'
  | 'fight'
  | 'lie'
  | 'spicy'
  | 'situationship'
  | 'quiz'
  | 'wyr'
  | 'choice'
  | 'funny'
  | 'secret'
  | 'deep'
  | 'soft'
  | 'hypothetical'
  | 'knowyou'
  | 'neutral';

export type CoverScope = 'couple' | 'friend' | 'any';

export type CoverTemplate = {
  tone: CoverTone;
  scope: CoverScope;
  text: string;
};

function line(tone: CoverTone, text: string, scope: CoverScope = 'couple'): CoverTemplate {
  return { tone, scope, text };
}

function join(
  tone: CoverTone,
  scope: CoverScope,
  heads: string[],
  tails: string[]
): CoverTemplate[] {
  const out: CoverTemplate[] = [];
  for (const head of heads) {
    for (const tail of tails) {
      out.push(line(tone, `${head} ${tail}`, scope));
    }
  }
  return out;
}

